# Builds one recipe per wiki analysis tutorial (.Rmd) for the datashield skill.
# Code chunks that contain a username or password are replaced by a pointer to
# the token-based login in SKILL.md, because agents must never handle passwords.
# Usage: Rscript build-recipes.R <analysis-tutorials-dir> <output-dir>

library(purrr)
library(stringr)

credential_pattern <- regex("password\\s*=|user\\s*=", ignore_case = TRUE)

credential_notice <- c("", paste(
  "> Login step omitted: log in with a token as described in SKILL.md",
  "(\"Credentials\"). Never put usernames or passwords in code run by an agent."
), "")

# Login is covered by SKILL.md itself, and this tutorial's prose lists demo passwords.
excluded_tutorials <- "logging-in.Rmd"

read_tutorial_title <- function(lines) {
  title_line <- str_subset(lines, "^title:")
  if (length(title_line) == 0) return(NA_character_)
  str_remove_all(str_remove(title_line[[1]], "^title:\\s*"), "^\"|\"$")
}

remove_yaml_header <- function(lines) {
  fences <- which(lines == "---")
  if (length(fences) >= 2 && fences[[1]] == 1) lines[-seq_len(fences[[2]])] else lines
}

split_into_blocks <- function(lines) {
  is_fence <- str_detect(lines, "^```")
  is_open <- cumsum(is_fence) %% 2 == 1
  starts_chunk <- is_fence & is_open
  follows_chunk <- c(FALSE, head(is_fence & !is_open, -1))
  split(lines, cumsum(starts_chunk | follows_chunk))
}

rewrite_block <- function(block) {
  is_chunk <- str_detect(block[[1]], regex("^```\\{r", ignore_case = TRUE))
  if (!is_chunk) return(block)
  if (str_detect(block[[1]], "(include|echo)\\s*=\\s*F(ALSE)?\\b")) return(character(0))
  if (any(str_detect(block, credential_pattern))) return(credential_notice)
  c("```r", block[-1])
}

build_recipe <- function(rmd_file, output_dir) {
  lines <- readLines(rmd_file, warn = FALSE)
  title <- read_tutorial_title(lines)
  body <- unlist(map(split_into_blocks(remove_yaml_header(lines)), rewrite_block))
  header <- c(
    paste0("# Recipe: ", title), "",
    paste0("Generated by `tools/build-recipes.R` from the DataSHIELD wiki tutorial `",
           basename(rmd_file), "`. Do not edit by hand; regenerate instead."), ""
  )
  output_file <- file.path(output_dir, str_replace(basename(rmd_file), "\\.Rmd$", ".md"))
  writeLines(c(header, body), output_file)
  list(file = basename(output_file), title = title)
}

write_recipe_index <- function(recipes, output_dir) {
  rows <- map_chr(recipes, \(r) paste0("- [", r$title, "](", r$file, ")"))
  writeLines(c("# Recipe index", "", rows), file.path(output_dir, "index.md"))
}

build_all_recipes <- function(tutorials_dir, output_dir) {
  dir.create(output_dir, showWarnings = FALSE, recursive = TRUE)
  rmd_files <- list.files(tutorials_dir, "\\.Rmd$", full.names = TRUE)
  rmd_files <- rmd_files[!basename(rmd_files) %in% excluded_tutorials]
  recipes <- map(rmd_files, build_recipe, output_dir)
  write_recipe_index(recipes, output_dir)
  message(length(recipes), " recipes -> ", output_dir)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop("Usage: Rscript build-recipes.R <analysis-tutorials-dir> <output-dir>")
build_all_recipes(args[[1]], args[[2]])

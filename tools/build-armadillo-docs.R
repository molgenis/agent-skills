# Converts the Armadillo service documentation (the mkdocs site's pages, in nav order) into
# plain Markdown reference files for the armadillo skill. mkdocs-only syntax is rewritten:
# admonitions become blockquotes, content tabs become bold labels, captions become plain text,
# and images are dropped because an agent cannot see them.
# Usage: Rscript build-armadillo-docs.R <armadillo-source-dir> <version> <output-dir>

library(purrr)
library(stringr)

excluded_titles <- c("About us", "License", "Contact")

# mkdocs.yml has !!python tags elsewhere that a YAML parser rejects, so only nav is parsed.
read_nav <- function(mkdocs_file) {
  lines <- readLines(mkdocs_file)
  start <- which(lines == "nav:")
  end <- start + which(str_detect(lines[-seq_len(start)], "^[a-z_]+:"))[[1]] - 1
  yaml::yaml.load(paste(lines[start:end], collapse = "\n"))$nav
}

flatten_nav <- function(entries, section = NA_character_) {
  map_dfr(entries, \(entry) {
    if (is.character(entry)) return(tibble::tibble(section = section, title = section, path = entry))
    title <- names(entry)
    if (is.list(entry[[1]])) return(flatten_nav(entry[[1]], title))
    tibble::tibble(section = section, title = title, path = entry[[1]])
  })
}

count_indent <- function(line) nchar(line) - nchar(str_trim(line, "left"))

# A block is every following line indented four spaces deeper than its marker, or blank.
find_block_end <- function(lines, start, indent) {
  end <- start
  for (i in seq_along(lines)[-seq_len(start)]) {
    if (nzchar(str_trim(lines[[i]])) && count_indent(lines[[i]]) < indent + 4) break
    end <- i
  }
  while (end > start && !nzchar(str_trim(lines[[end]]))) end <- end - 1
  end
}

format_block <- function(marker, body, indent) {
  pad <- strrep(" ", indent)
  admonition <- str_match(marker, "^\\s*(!!!|\\?\\?\\?\\+?)\\s+(\\w+)(?:\\s+\"(.*)\")?")
  if (!is.na(admonition[1, 1])) {
    label <- str_to_title(admonition[1, 3])
    heading <- if (is.na(admonition[1, 4])) label else paste0(label, ": ", admonition[1, 4])
    return(paste0(pad, "> ", c(paste0("**", heading, "**"), "", body)) |> str_trim("right"))
  }
  tab <- str_match(marker, "^\\s*===\\s+\"(.*)\"")[1, 2]
  c(paste0(pad, "**", tab, "**"), "", paste0(pad, body) |> str_trim("right"))
}

convert_blocks <- function(lines) {
  output <- character(0)
  i <- 1
  while (i <= length(lines)) {
    line <- lines[[i]]
    if (str_detect(line, "^\\s*(!!!|\\?\\?\\?\\+?|===)\\s")) {
      indent <- count_indent(line)
      end <- find_block_end(lines, i, indent)
      body <- str_sub(lines[seq_len(end - i) + i], indent + 5)
      output <- c(output, format_block(line, convert_blocks(body), indent))
      i <- end + 1
    } else {
      output <- c(output, line)
      i <- i + 1
    }
  }
  output
}

remove_mkdocs_syntax <- function(lines) {
  image <- "!\\[[^]]*\\]\\([^)]*\\)(\\{[^}]*\\})?"
  is_image_only <- str_detect(lines, paste0("^\\s*", image, "\\s*$"))
  is_caption_fence <- str_detect(lines, "^\\s*///\\s*(caption)?\\s*$")
  str_remove_all(lines[!is_image_only & !is_caption_fence], image)
}

build_page <- function(path, docs_dir, version, output_dir) {
  source_file <- file.path(docs_dir, path)
  output_name <- str_replace_all(str_remove(path, "^pages/"), "/", "-")
  header <- c(
    paste0("<!-- Generated by tools/build-armadillo-docs.R from molgenis-service-armadillo ",
           version, " docs/", path, ". Do not edit by hand; regenerate instead. -->"), ""
  )
  body <- convert_blocks(remove_mkdocs_syntax(readLines(source_file, warn = FALSE)))
  writeLines(c(header, body), file.path(output_dir, output_name))
  output_name
}

write_docs_index <- function(pages, version, output_dir) {
  rows <- pmap_chr(pages, \(section, title, file, ...) {
    label <- if (is.na(section) || title != section) title else paste(section, "overview")
    paste0("- ", if (is.na(section)) "" else paste0(section, ": "), "[", label, "](", file, ")")
  })
  writeLines(c(paste("# Armadillo", version, "documentation"), "",
               "Generated from the molgenis-service-armadillo documentation site.", "", rows),
             file.path(output_dir, "index.md"))
}

build_armadillo_docs <- function(source_dir, version, output_dir) {
  dir.create(output_dir, showWarnings = FALSE, recursive = TRUE)
  pages <- flatten_nav(read_nav(file.path(source_dir, "mkdocs.yml"))) |>
    dplyr::filter(!title %in% excluded_titles)
  pages$file <- map_chr(pages$path, build_page, file.path(source_dir, "docs"), version, output_dir)
  write_docs_index(pages, version, output_dir)
  message(nrow(pages), " pages -> ", output_dir)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3) stop("Usage: Rscript build-armadillo-docs.R <armadillo-source-dir> <version> <output-dir>")
build_armadillo_docs(args[[1]], args[[2]], args[[3]])

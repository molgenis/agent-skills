# Converts an ordered list of DataSHIELD wiki pages (Wiki.js Markdown or HTML) into plain
# Markdown reference files with an index. Links to listed pages point to the local files and
# all other wiki links to wiki.datashield.org, so the result reads without the wiki.
# Unpublished pages are refused, because they are drafts or superseded copies.
# Usage: Rscript build-wiki-guide.R <wiki-dir> <pages.txt> <output-dir>
# HTML pages need pandoc on the PATH.

library(purrr)
library(stringr)

wiki_url <- "https://wiki.datashield.org/en/"

find_page_file <- function(wiki_dir, page) {
  candidates <- file.path(wiki_dir, paste0(page, c(".md", ".html")))
  found <- candidates[file.exists(candidates)]
  if (length(found) == 0) stop("wiki page not found: ", page)
  found[[1]]
}

# Markdown pages have YAML front matter; HTML pages carry the same fields in a comment.
split_front_matter <- function(lines) {
  fences <- which(lines %in% c("---", "<!--", "-->"))
  if (length(fences) < 2 || fences[[1]] != 1) stop("page has no front matter")
  list(fields = yaml::yaml.load(paste(lines[2:(fences[[2]] - 1)], collapse = "\n")),
       body = lines[-seq_len(fences[[2]])])
}

convert_html <- function(body) {
  system2("pandoc", c("-f", "html", "-t", "gfm", "--wrap=none"), input = body, stdout = TRUE)
}

page_file_name <- function(page) paste0(str_replace_all(page, "/", "-"), ".md")

rewrite_links <- function(lines, pages) {
  str_replace_all(lines, "\\]\\((?:https://wiki\\.datashield\\.org)?/en/([^)#]+)(#[^)]*)?\\)", \(links) {
    parts <- str_match(links, "/en/([^)#]+)(#[^)]*)?\\)$")
    targets <- parts[, 2]
    anchors <- ifelse(is.na(parts[, 3]), "", parts[, 3])
    destinations <- ifelse(targets %in% pages, page_file_name(targets), paste0(wiki_url, targets))
    paste0("](", destinations, anchors, ")")
  })
}

# Drops Wiki.js callout classes ({.is-info}) and the previous/next navigation button blocks.
remove_wiki_markers <- function(lines) {
  nav_starts <- which(str_detect(lines, "^<div style=\"display: flex"))
  nav_ends <- map_int(nav_starts, \(start) start + which(lines[-seq_len(start)] == "</div>")[[1]])
  in_nav <- seq_along(lines) %in% unlist(map2(nav_starts, nav_ends, seq))
  lines[!in_nav & !str_detect(lines, "^\\s*\\{\\.is-[a-z]+\\}\\s*$")]
}

build_page <- function(page, wiki_dir, pages, output_dir) {
  file <- find_page_file(wiki_dir, page)
  parts <- split_front_matter(readLines(file, warn = FALSE))
  if (isFALSE(parts$fields$published)) stop("wiki page is unpublished: ", page)
  body <- if (str_ends(file, "\\.html")) convert_html(parts$body) else parts$body
  body <- rewrite_links(remove_wiki_markers(body), pages)
  header <- paste0("<!-- Generated by tools/build-wiki-guide.R from the DataSHIELD wiki page ",
                   page, ". Do not edit by hand; regenerate instead. -->")
  writeLines(c(header, "", body), file.path(output_dir, page_file_name(page)))
  parts$fields$title
}

build_wiki_guide <- function(wiki_dir, pages_file, output_dir) {
  pages <- discard(str_trim(readLines(pages_file)), \(page) page == "")
  dir.create(output_dir, showWarnings = FALSE, recursive = TRUE)
  titles <- map_chr(pages, build_page, wiki_dir, pages, output_dir)
  rows <- paste0("- [", titles, "](", page_file_name(pages), ")")
  writeLines(c("# DataSHIELD developer guide", "", "Generated from the DataSHIELD wiki.", "", rows),
             file.path(output_dir, "index.md"))
  message(length(pages), " pages -> ", output_dir)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3) stop("Usage: Rscript build-wiki-guide.R <wiki-dir> <pages.txt> <output-dir>")
build_wiki_guide(args[[1]], args[[2]], args[[3]])

# Copies source files from the latest GitHub release of each listed repo into one Markdown
# reference per example, so an agent sees how real DataSHIELD packages implement a pattern.
# Code is copied verbatim apart from roxygen @examples sections, which are removed.
# Set GITHUB_TOKEN to avoid the unauthenticated API rate limit.
# Usage: Rscript build-code-examples.R <examples.csv> <output-dir>

library(dplyr)
library(httr2)
library(purrr)
library(stringr)

script_dir <- dirname(sub("^--file=", "", grep("^--file=", commandArgs(), value = TRUE)))
source(file.path(script_dir, "github.R"))

read_release_file <- function(repo, tag, path) {
  request("https://raw.githubusercontent.com") |>
    req_url_path_append(repo, tag, path) |>
    req_perform() |>
    resp_body_string()
}

# Roxygen @examples in DataSHIELD packages log in to demo servers with a username and password,
# which agents must never use, and the function documentation is in references/functions/.
remove_roxygen_examples <- function(lines) {
  in_examples <- FALSE
  keep <- map_lgl(lines, \(line) {
    if (str_detect(line, "^#'\\s*@examples")) in_examples <<- TRUE
    else if (!str_detect(line, "^#'") || str_detect(line, "^#'\\s*@")) in_examples <<- FALSE
    !in_examples
  })
  lines[keep]
}

format_file_section <- function(repo, tag, path) {
  language <- if (str_ends(path, "\\.[Rr]")) "r" else "text"
  code <- remove_roxygen_examples(str_split_1(str_trim(read_release_file(repo, tag, path), "right"), "\n"))
  c(paste0("## ", repo, " ", tag, ": `", path, "`"), "", paste0("```", language), code, "```", "")
}

example_file_name <- function(example) paste0(str_replace_all(str_to_lower(example), "[^a-z0-9]+", "-"), ".md")

write_example <- function(files, example, output_dir) {
  header <- c(paste0("<!-- Generated by tools/build-code-examples.R. Do not edit by hand; ",
                     "regenerate instead. -->"), "", paste0("# ", example), "",
              "Roxygen `@examples` sections are removed; everything else is the released source.", "")
  sections <- unlist(pmap(select(files, repo, tag, path), format_file_section))
  writeLines(c(header, sections), file.path(output_dir, example_file_name(example)))
}

build_code_examples <- function(examples_file, output_dir) {
  examples <- readr::read_csv(examples_file, show_col_types = FALSE)
  releases <- map_dfr(unique(examples$repo), find_package_version)
  if (anyNA(releases$tag)) stop("every listed repo needs a GitHub release")
  examples <- left_join(examples, releases, by = "repo")
  dir.create(output_dir, showWarnings = FALSE, recursive = TRUE)
  groups <- split(examples, factor(examples$example, unique(examples$example)))
  iwalk(groups, write_example, output_dir)
  rows <- paste0("- [", names(groups), "](", example_file_name(names(groups)), ")")
  writeLines(c("# Code examples", "", "Source copied from the latest release of each package.", "", rows),
             file.path(output_dir, "index.md"))
  message(length(groups), " examples -> ", output_dir)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop("Usage: Rscript build-code-examples.R <examples.csv> <output-dir>")
build_code_examples(args[[1]], args[[2]])

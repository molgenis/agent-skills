# Lists every deprecated, defunct or superseded function in the generated function
# references, with the start of its description (where packages name the replacement),
# so a skill can ship this short list instead of the full references.
# Usage: Rscript build-lifecycle.R <functions-dir> <output.md>

library(purrr)
library(stringr)

read_entry_description <- function(lines, name) {
  start <- which(lines == paste("##", name))
  if (length(start) == 0) return("")
  text <- lines[seq(start + 2, length.out = 1)]
  str_trunc(str_squish(text), 300)
}

read_package_lifecycles <- function(reference_file) {
  lines <- readLines(reference_file)
  package <- str_match(lines[[1]], "^# (\\S+) (\\S+)")[, 2:3]
  rows <- str_match(lines, "^\\| `([^`]+)` \\|[^|]*\\| *(deprecated|defunct|superseded) *\\|")
  rows <- rows[!is.na(rows[, 1]), , drop = FALSE]
  map_chr(seq_len(nrow(rows)), \(i) paste0(
    "- `", rows[i, 2], "` (", package[[1]], " ", package[[2]], ", ", rows[i, 3], "): ",
    read_entry_description(lines, rows[i, 2])
  ))
}

build_lifecycle <- function(functions_dir, output_file) {
  entries <- unlist(map(list.files(functions_dir, "\\.md$", full.names = TRUE), read_package_lifecycles))
  header <- c("# Deprecated, defunct and superseded functions", "",
              "Generated by `tools/build-lifecycle.R` from the function references. Do not call a",
              "defunct function; prefer the replacement for a deprecated one.", "")
  writeLines(c(header, entries), output_file)
  message(length(entries), " functions -> ", output_file)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop("Usage: Rscript build-lifecycle.R <functions-dir> <output.md>")
build_lifecycle(args[[1]], args[[2]])
